class EntradaTablaSimbolos {
    final String nombre;
    final String tipo;
    final String rol;
    final int linea;
    final int columna;

    EntradaTablaSimbolos(String nombre, String tipo, String rol, int linea, int columna) {
        this.nombre = nombre;
        this.tipo = tipo;
        this.rol = rol;
        this.linea = linea;
        this.columna = columna;
    }
}
